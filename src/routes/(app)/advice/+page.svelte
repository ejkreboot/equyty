<script lang="ts">
	import { invalidateAll } from '$app/navigation';
	import { fade } from 'svelte/transition';
	import Icon from '$lib/components/Icon.svelte';
	import EmptyState from '$lib/components/EmptyState.svelte';
	import { money, relativeTime } from '$lib/format';
	import { toast } from '$lib/toast.svelte';

	let { data } = $props();

	type Payload = {
		headline: string;
		insights: { title: string; body: string; tone: 'positive' | 'neutral' | 'attention' }[];
		actions: { title: string; body: string; estimated_monthly_impact: number | null }[];
	};
	const payload = $derived(data.insight?.payload as Payload | undefined);

	let loading = $state(false);
	const TONE = {
		positive: { icon: 'trending_up', cls: 'positive' },
		neutral: { icon: 'info', cls: '' },
		attention: { icon: 'warning', cls: 'attention' }
	} as const;

	async function generate() {
		loading = true;
		try {
			const res = await fetch('/api/insights', { method: 'POST' });
			const body = await res.json().catch(() => null);
			if (!res.ok) throw new Error(body?.message ?? 'Could not generate insights');
			await invalidateAll();
		} catch (err) {
			toast(err instanceof Error ? err.message : 'Could not generate insights', 'error');
		} finally {
			loading = false;
		}
	}
</script>

<svelte:head><title>Advice · Equyty</title></svelte:head>

<div class="page narrow">
	<header class="page-header">
		<div class="title">
			<h1>Advice</h1>
			{#if data.insight}<span class="muted">Updated {relativeTime(data.insight.created_at)}</span>{/if}
		</div>
		<div class="actions">
			<button class="btn {payload ? '' : 'accent'}" onclick={generate} disabled={loading || data.accounts.length === 0}>
				<Icon name="auto_awesome" size={18} class={loading ? 'spin' : ''} />
				{loading ? 'Analyzing…' : payload ? 'Refresh insights' : 'Generate insights'}
			</button>
		</div>
	</header>

	{#if loading}
		<div class="loading" in:fade>
			<div class="skeleton" style="height: 38px; width: 70%"></div>
			<div class="grid-2">
				{#each [1, 2, 3, 4] as i (i)}<div class="skeleton" style="height: 120px"></div>{/each}
			</div>
			<p class="muted">Reading three months of spending, budgets and recurring bills…</p>
		</div>
	{:else if payload}
		<section class="hero card">
			<span class="badge accent"><Icon name="auto_awesome" size={14} />Your financial snapshot</span>
			<p class="headline">{payload.headline}</p>
		</section>

		<h2 class="section-title">What we noticed</h2>
		<div class="grid-2">
			{#each payload.insights as ins (ins.title)}
				{@const t = TONE[ins.tone] ?? TONE.neutral}
				<article class="card insight {t.cls}">
					<span class="ic"><Icon name={t.icon} size={19} /></span>
					<div>
						<h3>{ins.title}</h3>
						<p>{ins.body}</p>
					</div>
				</article>
			{/each}
		</div>

		<h2 class="section-title">Suggested next steps</h2>
		<ol class="actions-list card">
			{#each payload.actions as a, i (a.title)}
				<li>
					<span class="n">{i + 1}</span>
					<div>
						<h3>{a.title}</h3>
						<p>{a.body}</p>
					</div>
					{#if a.estimated_monthly_impact}
						<span class="badge positive impact">+{money(a.estimated_monthly_impact, { cents: false })}/mo</span>
					{/if}
				</li>
			{/each}
		</ol>
		<p class="disclaimer muted">
			<Icon name="info" size={14} />Generated by AI from aggregated totals — no account numbers are shared. This is educational, not professional financial advice.
		</p>
	{:else}
		<section class="card">
			<EmptyState
				icon="tips_and_updates"
				title="Personal insights, on demand"
				body={data.accounts.length
					? 'Get a plain-English read on your spending trends, budget pressure points and concrete ways to save — based on your last three months.'
					: 'Connect an account first so there’s data to analyze.'}
			>
				{#if data.accounts.length}
					<button class="btn accent" onclick={generate}><Icon name="auto_awesome" size={18} />Generate insights</button>
				{/if}
			</EmptyState>
		</section>
	{/if}
</div>

